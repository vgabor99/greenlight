static void set_pixel(int x, int y, int black)
{
    if (x < 0 || x >= EPD_WIDTH || y < 0 || y >= EPD_HEIGHT) {
        return;
    }
    uint8_t mask = 0x80 >> (x & 7);
    if (black) {
        fb[y * EPD_STRIDE + x / 8] &= ~mask;
    } else {
        fb[y * EPD_STRIDE + x / 8] |= mask;
    }
}

static void fill_rect(int x, int y, int w, int h, int black)
{
    for (int j = 0; j < h; j++) {
        for (int i = 0; i < w; i++) {
            set_pixel(x + i, y + j, black);
        }
    }
}

static void draw_char(int x, int y, char c)
{
    if (c < 0x20 || c > 0x7E) {
        c = '?';  /* control or non-ASCII byte in the received text */
    }
    const uint8_t *col = font[c - 0x20];
    for (int cx = 0; cx < 5; cx++) {
        for (int cy = 0; cy < 7; cy++) {
            if (col[cx] & (1 << cy)) {
                fill_rect(x + cx * SCALE, y + cy * SCALE, SCALE, SCALE, 1);
            }
        }
    }
}

static void draw_text(int x, int y, const char *s)
{
    for (; *s; s++, x += ADV) {
        draw_char(x, y, *s);
    }
}

/* One text row at the left margin; anything past COLS is cut off. */
static void row(int y, const char *fmt, ...)
{
    char    buf[COLS + 1];
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(buf, sizeof(buf), fmt, ap);
    va_end(ap);
    draw_text(X0, y, buf);
}

static void rx_row(int y, const render_rx_t *r)
{
    char t[12];
    snprintf(t, sizeof(t), "%lu.%lu", (unsigned long)(r->ms / 1000), (unsigned long)(r->ms % 1000 / 100));
    const zb_rx_t *e = &r->ev;
    unsigned long  h = e->hash;
    switch (e->kind) {
    case ZB_RX_LINE:
        row(y, "%s L%u %s", t, e->line, e->text);
        break;
    case ZB_RX_FOOTER:
        row(y, "%s F %s", t, e->text);
        break;
    case ZB_RX_COMMIT:
        switch (e->result) {
        case ZB_COMMIT_OK:        row(y, "%s C %06lX n=%u OK", t, h, e->count); break;
        case ZB_COMMIT_SAME:      row(y, "%s C %06lX n=%u SAME", t, h, e->count); break;
        case ZB_COMMIT_BAD_COUNT: row(y, "%s C %06lX n=%u BAD N", t, h, e->count); break;
        case ZB_COMMIT_REJECTED:
            if (e->tag < 0) {
                row(y, "%s C %06lX n=%u REJ L%u none", t, h, e->count, e->line);
            } else {
                row(y, "%s C %06lX n=%u REJ L%u=%06lX", t, h, e->count, e->line, (unsigned long)e->tag);
            }
            break;
        }
        break;
    }
}

const uint8_t *render_status(const render_view_t *v)
{
    memset(fb, 0xFF, sizeof(fb));

    /* Header: state left, wake counter and uptime right */
    char right[24];
    snprintf(right, sizeof(right), "w%lu %lu.%lus", (unsigned long)v->wake, (unsigned long)(v->uptime_ms / 1000),
             (unsigned long)(v->uptime_ms % 1000 / 100));
    row(Y_HEADER, "%s", v->state);
    draw_text(X0 + (COLS - (int)strlen(right)) * ADV, Y_HEADER, right);
    fill_rect(0, Y_RULE1, EPD_WIDTH, 2, 1);

    /* The snapshot on the panel */
    const zb_snapshot_t *s = &v->snap;
    if (s->hash == 0 && s->count == 0) {
        row(Y_SHOWN, "SHOWN nothing");
    } else {
        row(Y_SHOWN, "SHOWN %06lX  %u lines", (unsigned long)s->hash, s->count);
    }
    for (int i = 0; i < ZB_MAX_LINES; i++) {
        int y = Y_SHOWN + (i + 1) * PITCH;
        if (i < s->count) {
            row(y, "%d %s", i + 1, s->line[i]);
        } else if (i == 0 && s->hash != 0) {
            row(y, "  ALL OK");
        } else {
            row(y, "%d", i + 1);
        }
    }
    row(Y_SHOWN + 7 * PITCH, "F %s", s->footer);
    fill_rect(0, Y_RULE2, EPD_WIDTH, 2, 1);

    /* Received writes, newest first */
    for (int i = 0; i < v->rx_count && i < RENDER_RX_N; i++) {
        rx_row(Y_RX + i * PITCH, &v->rx[i]);
    }
    return fb;
}
